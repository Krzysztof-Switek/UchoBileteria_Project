"""
Import of the hall from the technical model export (sala_glowna/sala_glowna.json,
format "ucho-hall-layout" v1) into Room.geometry.

Source: metres, X to the right looking at the stage, Y towards the stage.
Target (canonical plan): centimetres, u = X·100 to the right, v = (Ymax − Y)·100
downwards — the stage at the top, the bar at the bottom.

On top of the plain conversion, `_owner_view` applies how the owner wants the
hall shown to buyers and staff (decisions of 2026-10-05) — the source file
stays untouched, it is generated by the technical model.
"""

SUPPORTED_FORMAT = "ucho-hall-layout"

BLOCKING = {
    "walls": "wall",
    "columns": "column",
    "stage": "stage",
    "stairs": "stairs",
    "platforms": "platform",
    "fixtures": "bar",
}
# Space kept free in front of a door/opening (evacuation), cm.
ENTRANCE_CLEARANCE_CM = 100
# Owner decisions 2026-10-05 (see _owner_view):
# rooms above the bar (office, VIP room) and the DJ booth are not drawn,
HIDDEN_OVERHEAD = {"VEN_ROOM_POM_TECH_23", "VEN_ROOM_POM_TECH_24", "VEN_PLATFORM_DJ"}
# only the main entrance and the stage door are shown (with new names),
SHOWN_ENTRANCES = {
    "VEN_OPENING_SALA_KORYTARZ": "Wejście główne",
    "VEN_DOOR_BACKSTAGE_SALA": "Wejście na scenę",
}
# the hall ends at the inner north (brick) wall — the corridor behind it is not shown,
NORTH_WALL_ID = "VEN_WALL_MUR_WEWN_PLN"
HIDDEN_WALLS = {"VEN_WALL_ZEWN_PLN"}
# the mezzanine reaches over the bar to the back wall (no edge line in front of the bar).
MEZZANINE_ID = "VEN_ROOM_ANTRESOLA"


class HallFormatError(ValueError):
    pass


def _items(value):
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def convert_hall(source: dict) -> dict:
    """Return {"name", "width_cm", "depth_cm", "geometry"} for a Room."""
    if source.get("format") != SUPPORTED_FORMAT or source.get("version") != 1:
        raise HallFormatError("Nieobsługiwany format pliku sali (oczekiwano ucho-hall-layout v1).")
    if (source.get("units") or {}).get("length") != "m":
        raise HallFormatError("Oczekiwano jednostek w metrach.")

    hall = source["hall"]
    outline_m = hall["outline"]
    xs = [p[0] for p in outline_m]
    ys = [p[1] for p in outline_m]
    x_min, y_max = min(xs), max(ys)

    def pt(p):
        return [round((p[0] - x_min) * 100, 1), round((y_max - p[1]) * 100, 1)]

    def shape(geometry: dict) -> dict:
        if geometry.get("shape") == "circle":
            u, v = pt(geometry["center"])
            return {"shape": "circle", "cx": u, "cy": v,
                    "r": round(geometry["diameter"] * 50, 1)}
        if geometry.get("shape") == "polyline":
            return {"shape": "polyline", "points": [pt(p) for p in geometry["points"]]}
        return {"shape": "polygon", "points": [pt(p) for p in geometry["points"]]}

    obstacles = []
    for category, kind in BLOCKING.items():
        for item in _items(source.get(category)):
            geometry = item.get("geometry")
            if not geometry:
                continue
            obstacles.append({
                "id": item["id"], "name": _short_name(item["name"]), "kind": kind,
                "blocking": True, "status": item.get("data_status", ""), **shape(geometry),
            })

    entrances = []
    for item in _items(source.get("entrances")):
        geometry = item.get("geometry")
        if not geometry:
            continue
        entrances.append({
            "id": item["id"], "name": _short_name(item["name"]),
            "clearance": ENTRANCE_CLEARANCE_CM, **shape(geometry),
        })

    context = []
    for item in _items(source.get("context_rooms")):
        context.append({"id": item["id"], "name": _short_name(item["name"]), "kind": "room",
                        "shape": "polygon", "points": [pt(p) for p in item["outline"]]})
    for item in _items(source.get("overhead")):
        points = item.get("outline") or (item.get("geometry") or {}).get("points")
        if not points or item.get("kind") == "structure_underside" or item["id"] in HIDDEN_OVERHEAD:
            continue
        context.append({"id": item["id"], "name": _short_name(item["name"]),
                        "kind": "overhead", "shape": "polygon",
                        "points": [pt(p) for p in points]})

    pit = None
    for item in _items(source.get("barrier")):
        geometry = item.get("geometry") or {}
        context.append({"id": item["id"], "name": _short_name(item["name"]), "kind": "barrier",
                        **shape(geometry)})
        stage = _items(source.get("stage"))
        if stage and geometry.get("points"):
            # The pit: between the barrier line and the stage front.
            (bx1, by), (bx2, _) = geometry["points"][0], geometry["points"][-1]
            stage_front = min(p[1] for p in stage[0]["geometry"]["points"])
            pit = {"points": [pt((bx1, by)), pt((bx2, by)), pt((bx2, stage_front)),
                              pt((bx1, stage_front))]}

    width_cm = round((max(xs) - x_min) * 100)
    depth_cm = round((y_max - min(ys)) * 100)
    unknown = [_short_name(i["name"]) for i in _items(source.get("unknown_geometry"))]
    unknown = [name for name in unknown if "DJ" not in name]
    geometry = {
        "outline": [pt(p) for p in outline_m],
        "obstacles": obstacles,
        "entrances": entrances,
        "context": context,
        "pit": pit,
        "unknown": unknown,
        "stage_side": "top",
        "generated": source.get("generated", ""),
    }
    width_cm = _owner_view(geometry) or width_cm
    return {"name": "Sala główna", "width_cm": width_cm, "depth_cm": depth_cm,
            "geometry": geometry}


def clip_polygon(points, axis: int, limit: float, keep_below: bool = True):
    """Sutherland–Hodgman clip of a polygon to u|v <= limit (or >= limit)."""
    def inside(p):
        return p[axis] <= limit if keep_below else p[axis] >= limit

    def cross(a, b):
        t = (limit - a[axis]) / ((b[axis] - a[axis]) or 1e-9)
        return [round(a[0] + t * (b[0] - a[0]), 1), round(a[1] + t * (b[1] - a[1]), 1)]

    out = []
    for i, cur in enumerate(points):
        prev = points[i - 1]
        if inside(cur):
            if not inside(prev):
                out.append(cross(prev, cur))
            out.append(list(cur))
        elif inside(prev):
            out.append(cross(prev, cur))
    deduped = []
    for p in out:
        if not deduped or p != deduped[-1]:
            deduped.append(p)
    if len(deduped) > 1 and deduped[0] == deduped[-1]:
        deduped.pop()
    # drop points lying on a straight run (also spikes that double back)
    changed = True
    while changed and len(deduped) > 3:
        changed = False
        for i in range(len(deduped)):
            a, b, c = deduped[i - 1], deduped[i], deduped[(i + 1) % len(deduped)]
            if (a[0] - b[0]) * (c[1] - b[1]) == (a[1] - b[1]) * (c[0] - b[0]):
                deduped.pop(i)
                changed = True
                break
    return deduped if len(deduped) >= 3 else []


def _owner_view(geometry: dict) -> int | None:
    """Apply the owner's presentation decisions (2026-10-05). Returns the new
    plan width (the outer face of the north wall) or None if the wall is missing."""
    obstacles = geometry["obstacles"]
    wall = next((o for o in obstacles if o["id"] == NORTH_WALL_ID), None)
    if wall is None:
        return None
    wall_us = [p[0] for p in wall["points"]]
    face, outer = min(wall_us), max(wall_us)  # inner face (hall side) / outer face

    # hall and everything in it end at the north wall
    geometry["outline"] = clip_polygon(geometry["outline"], 0, face)
    kept = []
    for o in obstacles:
        if o["id"] in HIDDEN_WALLS:
            continue
        if o["id"] == NORTH_WALL_ID:
            # the wall runs the whole length of the hall, also along the stage
            v_min = min(p[1] for q in obstacles if q["kind"] == "wall" and q.get("points")
                        for p in q["points"])
            v_max = max(p[1] for p in o["points"])
            o["points"] = [[face, v_min], [outer, v_min], [outer, v_max], [face, v_max]]
            o["name"] = "Ściana północna"
        elif o.get("shape") == "circle":
            if o["cx"] + o["r"] > face:
                continue
        else:
            limit = outer if o["kind"] == "wall" else face
            o["points"] = clip_polygon(o["points"], 0, limit)
            if not o["points"]:
                continue
        kept.append(o)
    geometry["obstacles"] = kept

    geometry["entrances"] = [
        {**e, "name": SHOWN_ENTRANCES[e["id"]]}
        for e in geometry["entrances"] if e["id"] in SHOWN_ENTRANCES
    ]

    context = []
    for c in geometry["context"]:
        if c["kind"] == "barrier":
            # demountable pit barriers: wall to wall across the whole hall
            v = c["points"][0][1]
            c["points"] = [[0, v], [face, v]]
            if geometry.get("pit"):
                stage_front = max(p[1] for p in geometry["pit"]["points"])
                stage_front = min(stage_front, v)
                top = min(p[1] for p in geometry["pit"]["points"])
                geometry["pit"] = {"points": [[0, top], [face, top], [face, v], [0, v]]}
            context.append(c)
            continue
        if c["id"] == MEZZANINE_ID:
            # the mezzanine runs over the whole bar to the back wall: its edge in
            # front of the bar is moved onto the back wall, so no dashed line
            # crosses the hall there (the model ends it at the bar front)
            back_wall = max(p[1] for p in geometry["outline"])
            bar_edge = max(p[1] for p in c["points"])
            points = [[p[0], back_wall if p[1] == bar_edge else p[1]] for p in c["points"]]
            c["points"] = clip_polygon(points, 0, face)
        elif c.get("shape") == "polygon":
            c["points"] = clip_polygon(c["points"], 0, face)
        if c.get("points"):
            context.append(c)
    geometry["context"] = context
    return round(outer)


def _short_name(name: str) -> str:
    """'10 Sala główna' -> 'Sala główna' (drops the room number of the inventory)."""
    name = name.strip()
    head, _, rest = name.partition(" ")
    if head.isdigit() and rest:
        return rest
    return name
